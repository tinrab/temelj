import { encodeBase64String } from "@temelj/string";
import { isString, isPlainObject } from "@temelj/value";
import { readFile, writeFile } from "node:fs/promises";

const VERSION = "2.0.2";

const FILE_URL = `https://cdn.jsdelivr.net/npm/character-entities@${VERSION}/index.js`;

async function main() {
  const input = process.argv[2];

  let source: string;

  if (input === undefined) {
    const response = await fetch(FILE_URL);

    if (!response.ok) {
      throw new Error(`Could not download ${FILE_URL}: ${response.status}`);
    }

    source = await response.text();
  } else {
    source = await readFile(input, "utf8");
  }

  const encoded = encodeBase64String(source);

  const { characterEntities: entities }: { characterEntities: unknown } = await import(
    `data:text/javascript;base64,${encoded}`
  );

  if (!isPlainObject(entities)) {
    throw new Error("character-entities did not export a record");
  }

  const entries = Object.entries(entities);

  for (const [name, replacement] of entries) {
    if (name.length === 0 || !isString(replacement)) {
      throw new Error(`Invalid character entity: ${name}`);
    }
  }

  entries.sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0));

  const output = `// Generated by scripts/generate-character-entities.ts from character-entities@${VERSION}.\n// Do not edit by hand.\n\nexport const NAMED_CHARACTER_REFERENCES: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(Object.fromEntries(entries), undefined, 2)});\n`;

  await writeFile(new URL("../src/character-entities.ts", import.meta.url), output);
}

void main();
